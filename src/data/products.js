// Helper functions for easy filtering
export function getProductById(id) {
  return PRODUCTS.find(p => p.id === id) || null;
}

export function getProductsByCategory(categoryId) {
  if (!categoryId || categoryId === 'all') return PRODUCTS;
  return PRODUCTS.filter(p => p.categoryId === categoryId);
}

export function getFeaturedProducts(limit = 8) {
  const featured = PRODUCTS.filter(p => p.featured);
  return limit ? featured.slice(0, limit) : featured;
}

export function getBestsellerProducts(limit = 8) {
  const bestsellers = PRODUCTS.filter(p => p.bestseller);
  return limit ? bestsellers.slice(0, limit) : bestsellers;
}

export function getNewArrivalProducts(limit = 8) {
  const newArrivals = PRODUCTS.filter(p => p.newArrival);
  return limit ? newArrivals.slice(0, limit) : newArrivals;
}
